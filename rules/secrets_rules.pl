# Universal Secret Detection Rules
# These rules apply to ALL files, regardless of programming language or config type.

my $calc_shannon_entropy = sub {
    my ($str) = @_;
    return 0 unless length($str);
    my %freq;
    $freq{$_}++ for split //, $str;
    my $len = length($str);
    my $entropy = 0;
    for my $count (values %freq) {
        my $p = $count / $len;
        $entropy -= $p * (log($p) / log(2));
    }
    return $entropy;
};

