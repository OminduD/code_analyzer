            # key, secret, token, auth, api, credential, private
            if ($content =~ /(?i)(?:api_?key|api_?token|secret_?key|access_?token|auth_?token|private_?token|client_?secret|app_?secret|custom_?secret(?:_?key)?)\s*[:=]\s*['"]([^'"]{20,})['"]/) {
                my $secret_val = $1;

                # Filter out obvious false positives (placeholders, templates, common false matches)
                return if $secret_val =~ /(?:placeholder|example|your_key|your_token|changeme|default|process\.env|undefined|null|true|false|123456789)/i;
                return if $secret_val =~ /^0+$/ || $secret_val =~ /^x+$/i;

                my $entropy = $calc_shannon_entropy->($secret_val);
                # A 20+ char random string has high Shannon entropy (> 3.8 bits/char)
                if ($entropy >= 3.80) {
                    return {
                        file     => $file,
                        line     => $token->{line_num},
                        rule_id  => 'SEC046',
                        message  => sprintf('High-entropy secret token or unidentified API key detected (Shannon entropy: %.2f bits/char, length: %d).', $entropy, length($secret_val)),
                        severity => 'HIGH',
                        fix      => 'Verify if this is an active production secret. If so, rotate it immediately and move it into a secure secret store.',
                        snippet  => $content,
                        type     => 'secret',
                        cwe      => 'CWE-798',
                    };
                }
            }
            return undef;
        },
    },
];
