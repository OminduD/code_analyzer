# TypeScript Vulnerability & Code Error Detection Rules

[
    # --- VULNERABILITIES ---
    {
        id       => 'TS001',
        type     => 'vulnerability',
        cwe      => 'CWE-95',
        pattern  => qr/\b(?:eval\s*\(|new\s+Function\s*\()/,
        message  => 'eval() or Function() constructor detected. Can execute arbitrary code.',
        severity => 'CRITICAL',
        fix      => 'Avoid use of eval() and Function(). Use JSON.parse() or standard logic.'
    },
    {
        id       => "TS002",
        type     => "vulnerability",
        cwe      => "CWE-79",
        pattern  => qr/\b(?:innerHTML|outerHTML)\s*=\s*(?!['"][^'"]*['"]\s*;)(?:\w+|\$|\+)/,
        message  => "Potential Cross-Site Scripting (XSS) via unescaped innerHTML/outerHTML assignment",
        severity => "HIGH",
        fix      => "Use textContent or a secure sanitization library like DOMPurify",
    },
    {
        id       => "TS003",
        type     => "vulnerability",
        cwe      => "CWE-78",
        pattern  => qr/\b(?:child_process\.(?:exec|execSync)|exec\s*\(|spawn\s*\(.*?shell\s*:\s*true)/,
        message  => "Command execution with shell enabled is vulnerable to command injection",
        severity => "CRITICAL",
        fix      => "Use execFile or spawn with shell=false and pass arguments as an array",
    },
    {
        id       => "TS004",
        type     => "vulnerability",
        cwe      => "CWE-89",
        pattern  => qr/\b(?:query|execute)\s*\(\s*["']SELECT|INSERT|UPDATE|DELETE\b.*?["']\s*\+/i,
        message  => "SQL query built with string concatenation is vulnerable to SQL Injection",
        severity => "CRITICAL",
        fix      => "Use parameterized queries or an ORM with type-safe query builders (e.g. Prisma, TypeORM)",
    },
    {
        id       => "TS005",
        type     => "vulnerability",
        cwe      => "CWE-1321",
        pattern  => qr/\b(?:__proto__|constructor\s*\[\s*['"]prototype['"]\])\b/,
        message  => "Potential Prototype Pollution vulnerability via __proto__ or prototype manipulation",
        severity => "HIGH",
        fix      => "Use Map instead of plain objects, or freeze Object.prototype",
    },
    {
        id       => "TS006",
        type     => "vulnerability",
        cwe      => "CWE-22",
        pattern  => qr/\bfs\.(?:readFile|readFileSync|createReadStream|writeFile|writeFileSync)\s*\(\s*(?:req\.|params|query|body)/,
        message  => "Path Traversal vulnerability: file system operation using unsanitized user input",
        severity => "HIGH",
        fix      => "Normalize and validate file paths using path.resolve() within allowed base directory",
    },
    {
        id       => "TS007",
        type     => "vulnerability",
        cwe      => "CWE-918",
        pattern  => qr/\b(?:axios\.(?:get|post)|fetch|http\.get|https\.get)\s*\(\s*(?:req\.|params|query|body)/,
        message  => "Potential Server-Side Request Forgery (SSRF) via unvalidated request URL",
        severity => "HIGH",
        fix      => "Validate target URLs against an explicit domain whitelist",
    },
    {
        id       => "TS008",
        type     => "vulnerability",
        cwe      => "CWE-697",
        pattern  => qr/\bas\s+any\b/,
        message  => "Bypassing TypeScript type checking using 'as any' disables compile-time safety and may conceal bugs",
        severity => "LOW",
        fix      => "Use proper interface typing, generics, or unknown with type guards instead of 'as any'",
    },
    {
        id       => "TS009",
        type     => "vulnerability",
        cwe      => "CWE-327",
        pattern  => qr/\bcrypto\.createHash\s*\(\s*['"](?:md5|sha1)['"]\s*\)/i,
        message  => "Use of weak cryptographic hash function (MD5/SHA1)",
        severity => "MEDIUM",
        fix      => "Use stronger hashing algorithms like SHA-256",
    },

    # --- CODE ERRORS & QUALITY BUGS ---
    {
        id       => "TSERR001",
        type     => "error",
        cwe      => "CWE-480",
        pattern  => qr/\bif\s*\(\s*[a-zA-Z0-9_\$]+\s*=\s*[^=]/,
        message  => "Accidental assignment in 'if' conditional statement instead of comparison",
        severity => "HIGH",
        fix      => "Replace single '=' assignment with strict equality comparison '==='",
    },
    {
        id       => "TSERR002",
        type     => "error",
        cwe      => "CWE-1025",
        pattern  => qr/[^!=]==\s*(?:null|undefined|0|false|true|['"])\b/,
        message  => "Use of loose equality '==' can lead to unintended type coercion bugs in TypeScript",
        severity => "LOW",
        fix      => "Use strict equality '===' instead of loose '=='",
    },
    {
        id       => "TSERR003",
        type     => "error",
        cwe      => "CWE-369",
        pattern  => qr/[a-zA-Z0-9_\$)]\s*[\/%]\s*0(?:\.0*)?(?!\d)/,
        message  => "Division or modulo by literal zero results in Infinity or NaN",
        severity => "HIGH",
        fix      => "Ensure divisor is non-zero before dividing",
    },
    {
        id       => "TSERR004",
        type     => "error",
        cwe      => "CWE-390",
        pattern  => qr/\bcatch\s*(?:\([^\)]*\))?\s*\{\s*\}/,
        message  => "Empty catch block silently swallows exceptions without logging or handling",
        severity => "MEDIUM",
        fix      => "Log the error or rethrow it",
    },
    {
        id       => "TSERR005",
        type     => "error",
        cwe      => "CWE-561",
        pattern  => qr/\b(?:return|throw)\b.*?;[ \t]*\S+/,
        message  => "Dead code detected immediately following return or throw statement",
        severity => "LOW",
        fix      => "Remove unreachable statements following return or throw",
    },
    {
        id       => "TS999",
        type     => "malware",
        pattern  => qr/(?i)(Software(?:\\|\/)Microsoft(?:\\|\/)Windows(?:\\|\/)CurrentVersion(?:\\|\/)Run|\.config(?:\\|\/)autostart)/,
        message  => "Potential malware persistence mechanism detected (Windows Run key or Linux autostart)",
        severity => "HIGH",
        fix      => "Remove auto-start functionality unless explicitly required by the application",
    }
